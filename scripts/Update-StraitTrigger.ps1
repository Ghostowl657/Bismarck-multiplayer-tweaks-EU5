# Regenerates in_game/common/scripted_triggers/bismarck_strait_triggers.txt from
# the installed game's strait crossings (adjacencies.csv rows of type "sea").
# Rerun after a game update changes the map, then review the diff.
param(
    [string]$GameDirectory = 'D:\SteamLibrary\steamapps\common\Europa Universalis V\game'
)

$ErrorActionPreference = 'Stop'
$adjacencies = Join-Path $GameDirectory 'in_game/map_data/adjacencies.csv'
$output = Join-Path $PSScriptRoot '../in_game/common/scripted_triggers/bismarck_strait_triggers.txt'

$pairs = [System.Collections.Generic.SortedSet[string]]::new([StringComparer]::Ordinal)
foreach ($row in Import-Csv -Path $adjacencies -Delimiter ';') {
    if ($row.Type -ne 'sea') { continue }
    $ends = @($row.From, $row.To) | Sort-Object
    [void]$pairs.Add("$($ends[0]);$($ends[1])")
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Generated by scripts/Update-StraitTrigger.ps1 from vanilla in_game/map_data/adjacencies.csv.')
$lines.Add('# Do not edit by hand. True when this location and prev (the location whose neighbors are being checked) are joined by a strait crossing. Call it directly inside a neighbor iterator.')
$lines.Add('bismarck_is_strait_crossing_to_prev = {')
$lines.Add('    OR = {')
foreach ($pair in $pairs) {
    $a, $b = $pair.Split(';')
    $lines.Add("        AND = { this = location:$a prev = location:$b }")
    $lines.Add("        AND = { this = location:$b prev = location:$a }")
}
$lines.Add('    }')
$lines.Add('}')

$utf8Bom = [System.Text.UTF8Encoding]::new($true)
[System.IO.File]::WriteAllText([IO.Path]::GetFullPath($output), ($lines -join "`n") + "`n", $utf8Bom)
Write-Output "Wrote $($pairs.Count) strait pairs to $output"
